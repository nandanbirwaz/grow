import { addDays, dayKey, eachDay, round } from '../lib/util.js';
import { getSettings } from './settings.js';
import { applyFilters, channelReport, dailySeries, funnel } from './metrics.js';
import { forecast } from './forecast.js';
import { budgetRecommendations, budgetSummary } from './budget.js';
import { experimentResults } from './experiments.js';
import { hourlyReferralSpikes, leaderboard } from './referrals.js';
import { computeAlerts } from './alerts.js';

/** Load everything for ONE dataset. Datasets never mix: every query is scoped by `dataset`. */
export async function loadData(store, dataset) {
  const [settings, registrations, events, ambassadors, spend, experiments] = await Promise.all([
    getSettings(store, dataset),
    store.find('registrations', { dataset }),
    store.find('events', { dataset }),
    store.find('ambassadors', { dataset }),
    store.find('spend', { dataset }),
    store.find('experiments', { dataset }),
  ]);
  return { dataset, settings, registrations, events, ambassadors, spend, experiments };
}

export function datasetLabel(dataset) {
  return dataset === 'demo'
    ? { dataset, simulated: true, label: 'SIMULATED DEMO DATA — generated by a seeded script, not real students or results' }
    : { dataset, simulated: false, label: 'Recorded data from this installation (no demo data included)' };
}

/** Compute all derived metrics. Forecast/budget/alerts use the full campaign; filters apply to reports. */
export function computeAll(data, filters, config) {
  const now = config.now();
  const tz = config.tzOffsetMin;
  const { settings } = data;
  const today = dayKey(now.getTime(), tz);

  const allDays = data.registrations.map((r) => r.day).sort();
  const startDateAssumed = !settings.startDate;
  const startDate = settings.startDate || allDays[0] || today;
  const endDate = addDays(startDate, settings.durationDays - 1);
  const asOfDate = today < startDate ? startDate : today > endDate ? endDate : today;

  const filtered = applyFilters(data, filters);
  const rangeFrom = filters.from || startDate;
  const rangeTo = filters.to || asOfDate;
  const daily = dailySeries(filtered.registrations, rangeFrom, rangeTo);

  // Global (unfiltered) numbers for forecast/budget/alerts
  const fullDaily = dailySeries(data.registrations, startDate, asOfDate);
  const chRegsAll = {};
  for (const r of data.registrations) chRegsAll[r.attribution.channel] = (chRegsAll[r.attribution.channel] || 0) + 1;

  const fc = forecast({
    daily: fullDaily, startDate, asOfDate, durationDays: settings.durationDays, target: settings.targetRegistrations,
    channelTotals: chRegsAll, minDays: settings.thresholds.forecastMinDays, startDateAssumed,
  });
  const budgetAll = budgetSummary({ spend: data.spend, registrations: data.registrations, capINR: settings.budgetCapINR, minRegs: settings.thresholds.minRegsPerChannel });
  const budgetFiltered = budgetSummary({ spend: filtered.spend, registrations: filtered.registrations, capINR: settings.budgetCapINR, minRegs: settings.thresholds.minRegsPerChannel });
  const channelsAll = channelReport(data.registrations, data.events, data.spend);
  const channels = channelReport(filtered.registrations, filtered.events, filtered.spend);
  const lb = leaderboard(data.ambassadors, data.registrations, settings.referralRules.pointsPerReferral);
  const spikes = hourlyReferralSpikes(data.registrations, data.ambassadors, settings.alertRules.referralSpikePerHour);
  const alerts = computeAlerts({
    rules: settings.alertRules, daily: fullDaily, asOfDate, budget: budgetAll, channels: channelsAll,
    referralSpikes: spikes, totalRegistrations: data.registrations.length, now,
  });
  const experiments = data.experiments.map((e) => experimentResults(e, data.events, settings.thresholds, { simulated: data.dataset === 'demo' }));

  const f = funnel(filtered.events);
  return {
    ...datasetLabel(data.dataset),
    generatedAt: now.toISOString(),
    filters: { from: filters.from || null, to: filters.to || null, channel: filters.channel || 'all' },
    campaign: { name: settings.campaignName, startDate, endDate, asOfDate, startDateAssumed, target: settings.targetRegistrations, durationDays: settings.durationDays, budgetCapINR: settings.budgetCapINR },
    totals: {
      registrations: filtered.registrations.length,
      registrationsAllTime: data.registrations.length,
      visitors: f.stages[0].count,
      visitToRegRate: f.overallRate,
      spendINR: budgetFiltered.actualTotalINR,
    },
    daily, funnel: f, channels, channelsAll, forecast: fc, budget: budgetAll, budgetFiltered,
    budgetRecommendations: budgetRecommendations(budgetAll),
    referrals: { leaderboard: lb, spikes },
    experiments, alerts,
    dataDays: eachDay(rangeFrom, rangeTo).length,
    _filtered: filtered,
  };
}

export const publicView = ({ _filtered, ...rest }) => rest;
