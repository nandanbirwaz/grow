import { useCallback, useEffect, useMemo, useState } from 'react';
import { ViewCtx } from './view.js';
import { api, hasToken, setToken, setUnauthorizedHandler } from './api.js';
import { viewQuery } from './lib/format.js';
import { Badge, Field, Loading, Notice, useApi } from './components/ui.jsx';
import Landing from './pages/Landing.jsx';
import Overview from './pages/Overview.jsx';
import Registrations from './pages/Registrations.jsx';
import Attribution from './pages/Attribution.jsx';
import Forecasts from './pages/Forecasts.jsx';
import Experiments from './pages/Experiments.jsx';
import Referrals from './pages/Referrals.jsx';
import Budget from './pages/Budget.jsx';
import Copilot from './pages/Copilot.jsx';
import ContentStudio from './pages/ContentStudio.jsx';
import ActivityLog from './pages/ActivityLog.jsx';

const PAGES = [
  ['overview', 'Overview', Overview], ['registrations', 'Registrations', Registrations], ['attribution', 'Attribution', Attribution],
  ['forecasts', 'Forecasts', Forecasts], ['experiments', 'Experiments', Experiments], ['referrals', 'Referrals', Referrals], ['budget', 'Budget', Budget],
  ['copilot', 'AI Copilot', Copilot], ['content', 'Content Studio', ContentStudio], ['activity', 'Activity Log', ActivityLog],
];

function Login({ onDone }) {
  const [email, setEmail] = useState(''); const [password, setPassword] = useState(''); const [err, setErr] = useState(null); const [busy, setBusy] = useState(false);
  return (
    <main className="login">
      <h1>Growth Hub</h1><p className="muted">Sign in to the organiser dashboard.</p>
      <form onSubmit={async (e) => { e.preventDefault(); setBusy(true); setErr(null); try { const r = await api.post('/api/auth/login', { email, password }); setToken(r.token); onDone(r.user); } catch (x) { setErr(x.message); setBusy(false); } }}>
        <Field label="Email" id="le"><input id="le" type="email" autoComplete="username" required value={email} onChange={(e) => setEmail(e.target.value)} /></Field>
        <Field label="Password" id="lp"><input id="lp" type="password" autoComplete="current-password" required value={password} onChange={(e) => setPassword(e.target.value)} /></Field>
        {err && <Notice tone="error">{err}</Notice>}
        <button className="btn primary" disabled={busy}>{busy ? 'Signing in…' : 'Sign in'}</button>
      </form>
      <p className="muted small"><a href="/">← Public registration page</a></p>
    </main>
  );
}

function DemoControls({ dataset, setDataset, canWrite, bump }) {
  const status = useApi('/api/demo/status', { deps: [bump.n] });
  const [busy, setBusy] = useState(false); const [msg, setMsg] = useState(null);
  const run = async (path, label) => {
    setBusy(true); setMsg(null);
    try { await api.post(path); setMsg(label); setDataset('demo'); bump.inc(); } catch (e) { setMsg(e.message); } finally { setBusy(false); }
  };
  const demoCount = status.data?.demo.registrations ?? 0;
  return (
    <div className={`banner ${dataset === 'demo' ? 'demo' : 'live'}`} role="status">
      <div>
        {dataset === 'demo'
          ? <><Badge kind="simulated" /> <strong>Demo mode — SIMULATED data.</strong> Generated by a seeded script; these are not real students, conversions or experiments.</>
          : <><Badge kind="recorded" /> <strong>Live data</strong> — only events and registrations recorded by this installation. {status.data && status.data.live.registrations === 0 && 'Nothing recorded yet.'}</>}
        {msg && <span className="small"> · {msg}</span>}
      </div>
      <div className="row">
        <div className="row" role="group" aria-label="Dataset">
          <button className="btn small" aria-pressed={dataset === 'live'} disabled={dataset === 'live'} onClick={() => setDataset('live')}>Live</button>
          <button className="btn small" aria-pressed={dataset === 'demo'} disabled={dataset === 'demo'} onClick={() => setDataset('demo')}>Demo{demoCount ? ` (${demoCount})` : ''}</button>
        </div>
        {canWrite && <>
          <button className="btn small" disabled={busy} onClick={() => run('/api/demo/load', 'Demo data loaded')}>Load demo data</button>
          <button className="btn small danger" disabled={busy || !demoCount} onClick={() => { if (window.confirm('Remove all SIMULATED demo data? Live data is not affected.')) run('/api/demo/reset', 'Demo data cleared'); }}>Reset demo</button>
        </>}
      </div>
    </div>
  );
}

function Dashboard({ user, onLogout }) {
  const [page, setPage] = useState(() => (window.location.hash.slice(2) || 'overview'));
  const [dataset, setDataset] = useState(() => { try { return sessionStorage.getItem('gh_dataset') || 'live'; } catch { return 'live'; } });
  const [from, setFrom] = useState(''); const [to, setTo] = useState(''); const [channel, setChannel] = useState('all');
  const [n, setN] = useState(0); const [open, setOpen] = useState(false);
  const canWrite = user.role === 'admin';
  useEffect(() => { const f = () => setPage(window.location.hash.slice(2) || 'overview'); window.addEventListener('hashchange', f); return () => window.removeEventListener('hashchange', f); }, []);
  useEffect(() => { try { sessionStorage.setItem('gh_dataset', dataset); } catch { /* ignore */ } }, [dataset]);
  const bump = useMemo(() => ({ n, inc: () => setN((x) => x + 1) }), [n]);
  const q = viewQuery({ dataset, from, to, channel });
  const qDataset = viewQuery({ dataset });
  const alerts = useApi(`/api/alerts${qDataset}`, { deps: [n, dataset] });
  const open_ = alerts.data?.alerts.filter((a) => !a.acknowledged && a.severity !== 'info').length || 0;
  const channels = useApi(`/api/attribution${qDataset}`, { deps: [n, dataset] });
  const chOptions = useMemo(() => ['all', ...(channels.data?.channels.map((c) => c.channel) || [])], [channels.data]);

  const ctx = useMemo(() => ({ dataset, from, to, channel, q, qDataset, canWrite, user, refresh: bump.inc, n, setPage }), [dataset, from, to, channel, q, qDataset, canWrite, user, bump, n]);
  const current = PAGES.find((p) => p[0] === page) || PAGES[0];
  const Page = current[2];
  const filterable = ['overview', 'registrations', 'attribution', 'budget'].includes(current[0]);

  return (
    <ViewCtx.Provider value={ctx}>
      <div className="shell">
        <aside className={`side ${open ? 'open' : ''}`} aria-label="Primary">
          <div className="brand">Growth Hub<small>AI Workshop campaign</small></div>
          <nav className="nav">
            {PAGES.map(([key, label]) => (
              <a key={key} href={`#/${key}`} aria-current={current[0] === key ? 'page' : undefined} onClick={() => setOpen(false)}>
                {label}{key === 'activity' && open_ > 0 && <span className="pill" aria-label={`${open_} open alerts`}>{open_}</span>}
              </a>
            ))}
          </nav>
          <p className="muted small" style={{ padding: '1rem .5rem 0' }}>{user.email}<br />Role: {user.role}</p>
          <div className="row" style={{ padding: '0 .5rem' }}><button className="btn small" onClick={onLogout}>Sign out</button><a className="small" href="/" target="_blank" rel="noreferrer">Public page</a></div>
        </aside>
        <div className="main">
          <div className="topbar"><button className="btn menu-btn" aria-label="Open menu" aria-expanded={open} onClick={() => setOpen((o) => !o)}>☰</button><h1 className="grow">{current[1]}</h1><button className="btn small" onClick={bump.inc}>Refresh</button></div>
          <DemoControls dataset={dataset} setDataset={setDataset} canWrite={canWrite} bump={bump} />
          {!canWrite && <Notice>You have read-only (analyst) access. Changes are disabled.</Notice>}
          {filterable && (
            <div className="filters" role="group" aria-label="Filters">
              <Field label="From" id="f-from"><input id="f-from" type="date" value={from} max={to || undefined} onChange={(e) => setFrom(e.target.value)} /></Field>
              <Field label="To" id="f-to"><input id="f-to" type="date" value={to} min={from || undefined} onChange={(e) => setTo(e.target.value)} /></Field>
              <Field label="Channel" id="f-ch"><select id="f-ch" value={channel} onChange={(e) => setChannel(e.target.value)}>{chOptions.map((c) => <option key={c} value={c}>{c === 'all' ? 'All channels' : c}</option>)}</select></Field>
              {(from || to || channel !== 'all') && <button className="btn small" onClick={() => { setFrom(''); setTo(''); setChannel('all'); }}>Clear filters</button>}
            </div>
          )}
          <Page key={`${dataset}`} />
        </div>
      </div>
    </ViewCtx.Provider>
  );
}

export default function App() {
  const isAdmin = window.location.pathname.startsWith('/admin');
  const [user, setUser] = useState(null); const [checking, setChecking] = useState(isAdmin && hasToken());
  const logout = useCallback(() => { setToken(null); setUser(null); }, []);
  useEffect(() => { setUnauthorizedHandler(() => setUser(null)); }, []);
  useEffect(() => {
    if (!isAdmin || !hasToken()) return;
    api.get('/api/auth/me').then((r) => setUser(r.user)).catch(() => setToken(null)).finally(() => setChecking(false));
  }, [isAdmin]);
  if (!isAdmin) return <Landing />;
  if (checking) return <Loading label="Checking session…" />;
  if (!user) return <Login onDone={setUser} />;
  return <Dashboard user={user} onLogout={logout} />;
}
